"""知识层：把散落在各处的接口知识连成一张可检索的图。

**为什么需要**

写用例时真正难的不是"怎么发请求"，是回答这几个问题：

- 这个接口的 `areaId` 到底对应哪张表的哪个列？
- 想断言"数据确实落库了"，该查哪张表、哪个字段？
- 这个接口历史上挂过吗？怎么修的？
- 这个模块里别人是怎么写断言的？

这些信息现在分散在四个地方，**互相之间没有连接**：

=============  ==================================================
来源           内容
=============  ==================================================
OpenAPI 快照   接口、参数、请求体字段、响应字段
表结构快照      库、表、列
用例文件        步骤、断言（含已写好的 ``db_query``）
接口定义        可复用的 path/method
=============  ==================================================

**核心是那条「字段↔列」的边。**

它是唯一能把"接口世界"和"数据库世界"连起来的边。有了它：

- 写落库断言不用猜列名
- 自愈时能判断"是接口改了还是表改了"
- 覆盖率能回答"这个接口写的数据有没有被验过"

**边的证据分三档**（``confidence``）：

======  =============================================  ====
置信度   来源                                            可信度
======  =============================================  ====
1.0     用例里已经写好的 ``db_query`` 断言             最高
0.9     命名规则 + 表名能对上（驼峰→下划线）             高
0.6     只有命名规则，表名是猜的                         中
======  =============================================  ====

低置信度的边不会自动使用，只作为"候选"给人确认。

**存储**

SQLite（标准库自带）：

- ``node`` / ``edge`` —— 图
- ``node_fts`` —— FTS5 全文索引（BM25 排序，不用装向量库）

为什么不直接上向量库：接口字段名是**精确词**，BM25 的召回质量
比通用 embedding 高，而且零依赖、可解释（能说清楚为什么召回它）。
"""

